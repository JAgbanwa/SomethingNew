"""Exact adapter from integer cubes to the user's squared rational-y equation.

The projective Elkies backend supplies integer cube triples. This module checks
the original equation independently and emits every distinct integer-x
representation obtained by choosing a same-parity pair of cube coordinates.
Rational-only points can also be checked, but are not generated by that backend.
"""
from __future__ import annotations

from fractions import Fraction
from itertools import permutations
from math import gcd, isqrt
import re
from typing import Iterable

TARGET = 375
N_RESIDUES_MOD27 = frozenset((2, 5, 14, 20, 23))


def integer(value: object, name: str = "integer") -> int:
    """Accept integers and decimal strings without any floating-point rounding."""
    if isinstance(value, bool) or not re.fullmatch(r"-?(0|[1-9][0-9]*)", str(value)):
        raise ValueError(f"{name} must be an exact decimal integer")
    return int(str(value))


def rational(value: object, name: str = "rational") -> Fraction:
    if isinstance(value, (bool, float)):
        raise ValueError(f"{name} must be an integer, fraction string or Fraction")
    try:
        return Fraction(value)
    except (ValueError, TypeError, ZeroDivisionError) as error:
        raise ValueError(f"{name} must be an exact rational") from error


def constants(n: int | str) -> tuple[int, int]:
    n = integer(n, "n")
    S = 6*n + 3
    N = 36*n**3 + 54*n**2 + 27*n - 58
    assert 6*N == S**3 - TARGET
    return S, N


def same_parity_pairs(triple: Iterable[int | str]) -> list[tuple[int, int, int]]:
    """Return distinct (A,B,C) choices with A<=B and A+B even.

    This combinatorial helper imposes no cube equation. Exchanging A and B
    changes only the sign of y, so one ordering suffices for canonical |y|.
    """
    xyz = tuple(integer(v, "coordinate") for v in triple)
    if len(xyz) != 3:
        raise ValueError("expected three coordinates")
    return sorted({(A, B, C) for A, B, C in permutations(xyz)
                   if A <= B and (A+B) % 2 == 0})


def check_point(n: int | str, x: int | str, y: Fraction | int | str) -> dict:
    """Classify a candidate using exact arithmetic and independently derived cubes.

    All exact integer and fraction values in the returned JSON-safe record are
    strings. Flags describe verified solutions, not proximity to the real curve.
    The sign of a supplied y is preserved; points_from_cube canonicalizes ±y.
    """
    n, x, y = integer(n, "n"), integer(x, "x"), rational(y, "y")
    S, N = constants(n)
    T = S+x
    if x == 0 or T == 0:
        raise ValueError("the original equation excludes x=0 and x=-(6n+3)")
    t = y*T
    R = x*(t*t-T*T)-N
    direct = y*y - (1 + Fraction(N, x*T*T))
    if direct != R/(x*T*T):
        raise ArithmeticError("the original and cleared residuals disagree")
    xyz = (-x-t, -x+t, Fraction(S+2*x))
    cube_sum = sum(z**3 for z in xyz)
    if cube_sum != TARGET-6*R:
        raise ArithmeticError("the cube identity disagrees with the residual")
    H = x*x*T*T+x*N
    exact = R == 0
    integral = exact and all(z.denominator == 1 for z in xyz)
    common = None
    primitive = False
    if exact:
        if H < 0 or isqrt(H)**2 != H or y*y != Fraction(H, x*x*T*T):
            raise ArithmeticError("an exact point failed the independent square test")
        if cube_sum != TARGET:
            raise ArithmeticError("an exact point failed the cube-sum check")
    if integral:
        common = gcd(gcd(abs(int(xyz[0])), abs(int(xyz[1]))), abs(int(xyz[2])))
        primitive = common == 1
        if common not in (1, 5):
            raise ArithmeticError("an integer 375 triple has an impossible gcd")
        if n % 27 not in N_RESIDUES_MOD27 or x % 3 != 1 or int(t) % 3 != 0:
            raise ArithmeticError("an integer cube lift violates a proved congruence")
    status = "primitive" if primitive else "cubes" if integral else "rational" if exact else "trial"
    return {
        "n": str(n), "x": str(x), "y": str(y), "t": str(t),
        "S": str(S), "N": str(N), "residual": str(R),
        "direct_discrepancy": str(direct), "square_integer_H": str(H),
        "cube_triple": [str(z) for z in xyz], "cube_sum": str(cube_sum),
        "cube_gcd": None if common is None else str(common),
        "exact": exact, "integral_lift": integral, "primitive": primitive,
        "status": status,
    }


def points_from_cube(triple: Iterable[int | str], *,
                     n_min: int | str | None = None,
                     n_max: int | str | None = None) -> list[dict]:
    """Map a verified 375 triple to all distinct same-parity pair representations.

    Selecting the third cube fixes x through the sum of the first two. Both
    orderings of those first two cubes give the same ±y pair, counted once by
    canonical nonnegative y. All integer cube triples have a same-parity pair.
    This applies no extra oddness or coprimality conditions on auxiliary X,Y.
    """
    xyz = tuple(integer(v, "cube coordinate") for v in triple)
    if len(xyz) != 3 or sum(v**3 for v in xyz) != TARGET:
        raise ValueError("expected exactly three integer cubes with sum 375")
    S = sum(xyz)
    if (S-3) % 6:
        raise ArithmeticError("a 375 triple has an impossible coordinate-sum class")
    n = (S-3)//6
    lo = None if n_min is None else integer(n_min, "n_min")
    hi = None if n_max is None else integer(n_max, "n_max")
    if lo is not None and hi is not None and lo > hi:
        raise ValueError("n_min must not exceed n_max")
    if lo is not None and n < lo or hi is not None and n > hi:
        return []
    found = {}
    for A, B, C in same_parity_pairs(xyz):
        x, t = -(A+B)//2, (B-A)//2
        T = S+x
        if x == 0 or T == 0:
            # In this target these poles cannot be solutions of the original
            # equation. Keep the adapter's domain exclusion explicit.
            continue
        y = abs(Fraction(t, T))
        record = check_point(n, x, y)
        if not record["exact"] or not record["integral_lift"]:
            raise ArithmeticError("cube-to-equation mapping failed exact verification")
        if sorted(Fraction(v) for v in record["cube_triple"]) != sorted(map(Fraction, xyz)):
            raise ArithmeticError("cube-to-equation mapping changed the cube multiset")
        record["source_cube_triple"] = [str(v) for v in xyz]
        record["source"] = "elkies-integer-cube-lift"
        found[(x, y)] = record
    return [found[key] for key in sorted(found)]


def rational_point_at(n: int | str, x: int | str) -> dict | None:
    """Check a single integer x for rational y using the exact square criterion.

    This is a point checker, not an exhaustive rational-only search engine.
    None means that x has no rational y; a nonreal point also returns None.
    """
    n, x = integer(n, "n"), integer(x, "x")
    S, N = constants(n)
    T = S+x
    if x == 0 or T == 0:
        raise ValueError("the original equation excludes x=0 and x=-(6n+3)")
    H = x*x*T*T+x*N
    if H < 0:
        return None
    root = isqrt(H)
    if root*root != H:
        return None
    return check_point(n, x, Fraction(root, abs(x*T)))
