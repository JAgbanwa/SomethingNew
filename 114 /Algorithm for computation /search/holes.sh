#!/bin/bash
cd "$(dirname "$0")"
sgn=$1; part=$2
if [ "$sgn" = "1" ]; then
  R=(21744001:25000000 32498001:37500000 43922001:50000000 55648001:62500000 67588001:75000000 79670001:87500000 91806001:92000000)
else
  R=(21750001:25000000 32484001:37500000 43884001:50000000 55666001:62500000 67586001:75000000 79674001:87500000 91810001:92000000)
fi
i=0
for r in "${R[@]}"; do
  lo=${r%%:*}; hi=${r##*:}
  if [ $((i % 2)) -eq $part ]; then ./search_sv4 $lo $hi $sgn; fi
  i=$((i+1))
done
